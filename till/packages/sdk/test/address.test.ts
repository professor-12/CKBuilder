import assert from "node:assert/strict";
import { describe, it } from "node:test";

import { ccc } from "@ckb-ccc/core";

import { addressToLockScript } from "../src/address.ts";
import { TillError } from "../src/errors.ts";

/**
 * Differential testing against CCC: any address CCC generates, the pure
 * decoder must decode to the identical script. CCC is the SDK every CKB
 * wallet in this stack builds transactions with, so agreement with it is
 * the property that matters.
 */
describe("addressToLockScript · differential vs CCC", () => {
  const mainnet = new ccc.ClientPublicMainnet();
  const testnet = new ccc.ClientPublicTestnet();

  const scripts = [
    {
      // standard secp256k1 lock shape
      codeHash:
        "0x9bd7e06f3ecf4be0f2fcd2188b23f1b9fcc88e5d4b65a8637b17723bbda3cce8",
      hashType: "type" as const,
      args: "0x8e42b1999f265a0078503c4acec4d5e134534297",
    },
    {
      // data1 code hash with long args (spore-like)
      codeHash:
        "0x4a4dce1df3dffff7f8b2cd7dff7303df3b6150c9788cb75dcf6747247132b9f5",
      hashType: "data1" as const,
      args: "0x" + "ab".repeat(32),
    },
    {
      // empty args
      codeHash: "0x" + "11".repeat(32),
      hashType: "data" as const,
      args: "0x",
    },
    {
      // data2 hash type
      codeHash: "0x" + "e2".repeat(32),
      hashType: "data2" as const,
      args: "0x00ff",
    },
  ];

  for (const [client, network] of [
    [mainnet, "ckb"],
    [testnet, "ckt"],
  ] as const) {
    for (const script of scripts) {
      it(`round-trips ${script.hashType} script on ${network}`, () => {
        const address = ccc.Address.fromScript(
          ccc.Script.from(script),
          client,
        ).toString();
        const decoded = addressToLockScript(address, network);
        assert.equal(decoded.codeHash, script.codeHash);
        assert.equal(decoded.hashType, script.hashType);
        assert.equal(decoded.args, script.args);
      });
    }
  }
});

describe("addressToLockScript · real addresses", () => {
  it("decodes the USDI issuer's mainnet address to the secp lock", () => {
    const decoded = addressToLockScript(
      "ckb1qzda0cr08m85hc8jlnfp3zer7xulejywt49kt2rr0vthywaa50xwsqw9p2zfraa25z62ll2h46pn5njgwget6gc5lpq89",
      "ckb",
    );
    // Omnilock-or-secp is not assumed; just assert structural sanity and
    // that decoding agrees with CCC on the same string.
    const viaCcc = ccc.Address.fromString(
      "ckb1qzda0cr08m85hc8jlnfp3zer7xulejywt49kt2rr0vthywaa50xwsqw9p2zfraa25z62ll2h46pn5njgwget6gc5lpq89",
      new ccc.ClientPublicMainnet(),
    );
    return viaCcc.then((a) => {
      assert.equal(decoded.codeHash, a.script.codeHash);
      assert.equal(decoded.hashType, a.script.hashType);
      assert.equal(decoded.args, a.script.args);
    });
  });
});

describe("addressToLockScript · refusals", () => {
  // A guaranteed-valid testnet address, generated by CCC itself.
  const valid = ccc.Address.fromScript(
    ccc.Script.from({
      codeHash:
        "0x9bd7e06f3ecf4be0f2fcd2188b23f1b9fcc88e5d4b65a8637b17723bbda3cce8",
      hashType: "type",
      args: "0x8e42b1999f265a0078503c4acec4d5e134534297",
    }),
    new ccc.ClientPublicTestnet(),
  ).toString();

  it("decodes the valid control address (the refusal tests mean something)", () => {
    const decoded = addressToLockScript(valid, "ckt");
    assert.equal(decoded.args, "0x8e42b1999f265a0078503c4acec4d5e134534297");
  });

  it("refuses an address from the other network", () => {
    assert.throws(() => addressToLockScript(valid, "ckb"), TillError);
  });

  it("refuses a mistyped character via checksum", () => {
    const typo = valid.slice(0, -1) + (valid.endsWith("2") ? "3" : "2");
    assert.throws(() => addressToLockScript(typo, "ckt"), TillError);
  });

  it("refuses mixed case, junk, and truncation", () => {
    assert.throws(() => addressToLockScript(valid.toUpperCase().slice(0, 20) + valid.slice(20), "ckt"), TillError);
    assert.throws(() => addressToLockScript("ckt1", "ckt"), TillError);
    assert.throws(() => addressToLockScript("not-an-address", "ckt"), TillError);
    assert.throws(() => addressToLockScript(valid.slice(0, 30), "ckt"), TillError);
  });
});
